'use strict';

/**
 * Contract for the FlightFabric MSFS 2024 toolbar package.
 *
 * Shared by the package build (msfs-toolbar-panel/tools/build-package.js)
 * and the desktop installer (electron/msfs-toolbar-panel-installer.js) so
 * the assembled package, the installed copy and the ownership checks all
 * agree on names, identity and file lists. Pure functions only: no
 * filesystem access, no Electron.
 */

const path = require('node:path');

// Community folder directory name. Also the MSFS package name.
const PACKAGE_DIRECTORY_NAME = 'flightfabric-toolbar';

// manifest.json identity. Install, update and remove refuse to touch a
// same-name directory whose manifest does not carry exactly this identity.
const PACKAGE_IDENTITY = Object.freeze({
  title: 'FlightFabric Toolbar',
  creator: 'FlightFabric',
  manufacturer: 'FlightFabric',
});

const PANEL_ID = 'FLIGHTFABRIC_TOOLBAR_PANEL';
const PANEL_NAME = 'FlightFabric';
const PANEL_ICON_ID = 'ICON_TOOLBAR_FLIGHTFABRIC';
const PANEL_HTML_DIR = 'html_ui/InGamePanels/FlightFabric';
const PANEL_URL = 'html_UI/InGamePanels/FlightFabric/FlightFabric.html';
const SPB_FILE = `InGamePanels/${PACKAGE_DIRECTORY_NAME}.spb`;
const CONFIG_FILE = `${PANEL_HTML_DIR}/FlightFabric.config.js`;
const MANIFEST_FILE = 'manifest.json';
const LAYOUT_FILE = 'layout.json';

// Every payload file the package ships, as slash-separated relative paths.
// layout.json lists exactly these; manifest.json and layout.json themselves
// are metadata and are never listed.
const PACKAGE_PAYLOAD_FILES = Object.freeze([
  SPB_FILE,
  `${PANEL_HTML_DIR}/FlightFabric.html`,
  `${PANEL_HTML_DIR}/FlightFabric.js`,
  `${PANEL_HTML_DIR}/FlightFabric.css`,
  CONFIG_FILE,
  // Native MSFS 2024 toolbar icon lookup and the legacy lookup path.
  `html_ui/icons/toolbar/${PANEL_ICON_ID}.svg`,
  `html_ui/Textures/Menu/toolbar/${PANEL_ICON_ID}.svg`,
]);

const HTTP_PORT_PLACEHOLDER = '__FF_HTTP_PORT__';
const WS_PORT_PLACEHOLDER = '__FF_WS_PORT__';
const CONFIG_GLOBAL = 'FLIGHTFABRIC_TOOLBAR_CONFIG';

// Windows FILETIME: 100 ns intervals since 1601-01-01, as layout.json expects.
// Returned as a digit string because the value exceeds Number.MAX_SAFE_INTEGER.
const FILETIME_EPOCH_OFFSET_MS = 11644473600000n;

function toFileTime(mtimeMs) {
  const millis = BigInt(Math.max(0, Math.floor(Number(mtimeMs) || 0)));
  return ((millis + FILETIME_EPOCH_OFFSET_MS) * 10000n).toString();
}

function isValidTcpPort(value) {
  return Number.isInteger(value) && value >= 1024 && value <= 65535;
}

function isValidPackageVersion(value) {
  return typeof value === 'string' && /^\d+\.\d+\.\d+$/.test(value);
}

function assertPorts(ports) {
  const httpPort = Number(ports && ports.httpPort);
  const wsPort = Number(ports && ports.wsPort);
  if (!isValidTcpPort(httpPort) || !isValidTcpPort(wsPort)) {
    throw new Error('Toolbar package ports must be integers from 1024 through 65535');
  }
  if (httpPort === wsPort) {
    throw new Error('Toolbar package HTTP and WebSocket ports must differ');
  }
  return { httpPort, wsPort };
}

/**
 * Render the small configuration script the simulator loader reads. The
 * source package keeps the placeholders; the installer substitutes the
 * user's ports into its staged copy.
 */
function renderConfigSource({ httpPort, wsPort, packageVersion }) {
  const httpText = httpPort === HTTP_PORT_PLACEHOLDER ? httpPort : String(assertPorts({ httpPort, wsPort }).httpPort);
  const wsText = wsPort === WS_PORT_PLACEHOLDER ? wsPort : String(assertPorts({ httpPort, wsPort }).wsPort);
  if (!isValidPackageVersion(packageVersion)) {
    throw new Error(`Toolbar package version must be MAJOR.MINOR.PATCH, got ${String(packageVersion)}`);
  }
  return [
    '// Generated by FlightFabric. Reinstall the toolbar package from FlightFabric',
    '// Settings if the FlightFabric network ports change.',
    `window.${CONFIG_GLOBAL} = Object.freeze({`,
    `  httpPort: ${httpText},`,
    `  wsPort: ${wsText},`,
    `  packageVersion: ${JSON.stringify(packageVersion)},`,
    '});',
    '',
  ].join('\n');
}

function renderConfigTemplate(packageVersion) {
  return renderConfigSource({
    httpPort: HTTP_PORT_PLACEHOLDER,
    wsPort: WS_PORT_PLACEHOLDER,
    packageVersion,
  });
}

function substituteConfigPorts(templateSource, ports) {
  const { httpPort, wsPort } = assertPorts(ports);
  if (typeof templateSource !== 'string'
      || !templateSource.includes(HTTP_PORT_PLACEHOLDER)
      || !templateSource.includes(WS_PORT_PLACEHOLDER)) {
    throw new Error('Toolbar package config template is missing its port placeholders');
  }
  return templateSource
    .split(HTTP_PORT_PLACEHOLDER).join(String(httpPort))
    .split(WS_PORT_PLACEHOLDER).join(String(wsPort));
}

/**
 * Read the ports and version back out of an installed config script.
 * Returns null when the file is not one we generated.
 */
function parseConfigSource(source) {
  if (typeof source !== 'string' || source.length > 4096) return null;
  const http = /httpPort:\s*(\d{4,5}),/.exec(source);
  const ws = /wsPort:\s*(\d{4,5}),/.exec(source);
  const version = /packageVersion:\s*"(\d+\.\d+\.\d+)",/.exec(source);
  if (!http || !ws || !version || !source.includes(`window.${CONFIG_GLOBAL}`)) return null;
  const httpPort = Number(http[1]);
  const wsPort = Number(ws[1]);
  if (!isValidTcpPort(httpPort) || !isValidTcpPort(wsPort)) return null;
  return { httpPort, wsPort, packageVersion: version[1] };
}

function buildManifest({ packageVersion, totalPackageSize, minimumGameVersion = '1.0.0' }) {
  if (!isValidPackageVersion(packageVersion)) {
    throw new Error(`Toolbar package version must be MAJOR.MINOR.PATCH, got ${String(packageVersion)}`);
  }
  if (!Number.isInteger(totalPackageSize) || totalPackageSize < 0) {
    throw new Error('Toolbar package total size must be a non-negative integer');
  }
  return {
    dependencies: [],
    content_type: 'MISC',
    title: PACKAGE_IDENTITY.title,
    manufacturer: PACKAGE_IDENTITY.manufacturer,
    creator: PACKAGE_IDENTITY.creator,
    package_version: packageVersion,
    minimum_game_version: minimumGameVersion,
    package_order_hint: 'CUSTOM_INSTRUMENT',
    release_notes: {
      neutral: {
        LastUpdate: '',
        OlderHistory: '',
      },
    },
    total_package_size: String(totalPackageSize).padStart(20, '0'),
  };
}

/**
 * Build layout.json from stat results. `entries` is [{ path, size, mtimeMs }]
 * in payload order; the sim reads sizes strictly, so callers stat the files
 * they actually wrote.
 */
function buildLayout(entries) {
  const content = entries.map((entry) => {
    if (!PACKAGE_PAYLOAD_FILES.includes(entry.path)) {
      throw new Error(`Unexpected toolbar package payload file: ${entry.path}`);
    }
    if (!Number.isInteger(entry.size) || entry.size < 0) {
      throw new Error(`Toolbar package payload size must be a non-negative integer: ${entry.path}`);
    }
    return { path: entry.path, size: entry.size, date: toFileTime(entry.mtimeMs) };
  });
  const listed = content.map((entry) => entry.path);
  for (const required of PACKAGE_PAYLOAD_FILES) {
    if (!listed.includes(required)) throw new Error(`Toolbar package layout is missing ${required}`);
  }
  return { content };
}

/**
 * layout.json text. Written by hand so the FILETIME dates are emitted as
 * exact integers; JSON.stringify would round them to double precision.
 */
function serializeLayout(layout) {
  const entries = layout.content.map((entry) => {
    if (!/^\d+$/.test(String(entry.date))) throw new Error(`Toolbar package layout date is not an integer: ${entry.path}`);
    return [
      '    {',
      `      "path": ${JSON.stringify(entry.path)},`,
      `      "size": ${entry.size},`,
      `      "date": ${entry.date}`,
      '    }',
    ].join('\n');
  });
  return `{\n  "content": [\n${entries.join(',\n')}\n  ]\n}\n`;
}

function serializeManifest(manifest) {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

function isOwnedManifest(manifest) {
  return Boolean(manifest)
    && typeof manifest === 'object'
    && manifest.title === PACKAGE_IDENTITY.title
    && manifest.creator === PACKAGE_IDENTITY.creator;
}

function toPosixPath(value) {
  return String(value).split(path.sep).join('/');
}

module.exports = {
  CONFIG_FILE,
  CONFIG_GLOBAL,
  HTTP_PORT_PLACEHOLDER,
  LAYOUT_FILE,
  MANIFEST_FILE,
  PACKAGE_DIRECTORY_NAME,
  PACKAGE_IDENTITY,
  PACKAGE_PAYLOAD_FILES,
  PANEL_HTML_DIR,
  PANEL_ICON_ID,
  PANEL_ID,
  PANEL_NAME,
  PANEL_URL,
  SPB_FILE,
  WS_PORT_PLACEHOLDER,
  assertPorts,
  buildLayout,
  buildManifest,
  isOwnedManifest,
  isValidPackageVersion,
  isValidTcpPort,
  parseConfigSource,
  renderConfigSource,
  renderConfigTemplate,
  serializeLayout,
  serializeManifest,
  substituteConfigPorts,
  toFileTime,
  toPosixPath,
};
