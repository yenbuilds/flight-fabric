// Compile shared app preset rules and the small DOM view for MSFS Coherent.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(root, 'frontend/package.json'));
const { build } = require('esbuild');
export async function buildToolbarPresets() {
  return buildPanel('presets', 'FlightFabricToolbarPresets');
}
export async function buildToolbarTaxi() {
  return buildPanel('taxi', 'FlightFabricToolbarTaxi');
}
async function buildPanel(name, globalName) {
  const result = await build({ entryPoints: [path.join(root, 'frontend/src/aircraft/toolbar-' + name + '.js')],
    bundle: true, write: false, format: 'iife', globalName,
    target: 'es2017', charset: 'ascii', legalComments: 'none' });
  return '// Generated by scripts/build-toolbar-presets.mjs. Do not edit.\n' + result.outputFiles[0].text;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const [name, generate] of [['presets', buildToolbarPresets], ['taxi', buildToolbarTaxi]]) {
    const output = path.join(root, 'frontend/toolbar/' + name + '.js');
    const expected = await generate();
    if (process.argv.includes('--check')) {
      if (fs.readFileSync(output, 'utf8').replace(/\r\n/g, '\n') !== expected) throw new Error('Run node scripts/build-toolbar-presets.mjs');
    } else fs.writeFileSync(output, expected);
  }
}
