#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const ROOT = path.resolve(__dirname, '..');
const SUPPORT_URL = 'https://www.flightfabric.com/support/';

function supportDestination(config) {
  const value = config?.destination;
  if (typeof value !== 'string' || value.length > 2048 || /[\s\\$"'{}<>]/.test(value)) {
    throw new Error('Support destination must be a literal HTTPS URL.');
  }
  const url = new URL(value);
  if (url.protocol !== 'https:' || url.username || url.password || url.port
      || (['flightfabric.com', 'www.flightfabric.com'].includes(url.hostname)
        && /^\/support(?:\/|$)/.test(url.pathname))) {
    throw new Error('Support destination must be HTTPS without credentials, a custom port or a redirect loop.');
  }
  return url.href;
}

function syncSupportLink({ root = ROOT, check = false } = {}) {
  const destination = supportDestination(JSON.parse(fs.readFileSync(path.join(root, 'site/support-link.json'), 'utf8')));
  const htmlUrl = destination.replace(/&/g, '&amp;');
  const outputs = new Map([
    ['site/flightfabric/support/index.html', `<!doctype html>
<!-- Generated by scripts/sync-support-link.js from site/support-link.json. -->
<html lang="en">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta name="robots" content="noindex, nofollow">
    <meta name="referrer" content="no-referrer">
    <meta http-equiv="refresh" content="0; url=${htmlUrl}">
    <title>Support FlightFabric</title>
    <link rel="stylesheet" href="/styles.css">
  </head>
  <body>
    <main class="shell download-fallback">
      <a class="brand" href="/">FlightFabric</a>
      <h1>Thank you for supporting FlightFabric.</h1>
      <p>Opening the support page. If it doesn't open automatically, use the button below.</p>
      <a id="support-destination" class="button button--primary" href="${htmlUrl}" rel="noreferrer">Continue to support</a>
      <p>Your support helps keep FlightFabric free and improving.</p>
    </main>
  </body>
</html>
`],
    ['site/nginx/flightfabric-support.conf', `# Generated by scripts/sync-support-link.js from site/support-link.json.
# Include inside the existing HTTPS server for www.flightfabric.com.
# Deliberately do not forward request parameters or accept a target from callers.
${['/support', '/support/', '/support/index.html'].map(route => `location = ${route} {
    add_header Cache-Control "no-store" always;
    add_header Referrer-Policy "no-referrer" always;
    return 302 "${destination}";
}`).join('\n\n')}
`],
  ]);
  const changed = [];
  for (const [file, content] of outputs) {
    const target = path.join(root, file);
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current.replace(/\r\n/g, '\n') === content) continue;
    changed.push(file);
    if (!check) {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, content, 'utf8');
    }
  }
  if (check && changed.length) throw new Error(`Run node scripts/sync-support-link.js; stale support redirects: ${changed.join(', ')}`);
  return changed;
}

if (require.main === module) {
  try {
    if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node scripts/sync-support-link.js [--check]');
    const changed = syncSupportLink({ check: process.argv.includes('--check') });
    console.log(`Support redirect: ${changed.length} changed file(s).`);
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}

module.exports = { SUPPORT_URL, supportDestination, syncSupportLink };
